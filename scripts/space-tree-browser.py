"""Read-only sidebar grouping against an isolated mock, with all writes blocked."""
import copy, json, os, re, unittest, urllib.request
from playwright.sync_api import sync_playwright, expect
from browser_common import BASE, launch, screenshot_dir

class SpaceTree(unittest.TestCase):
    def test_groups_search_and_selection(self):
        with urllib.request.urlopen(os.environ.get('TAXIS_FIXTURE_URL', BASE) + '/api/hierarchy', timeout=10) as response: body = json.load(response)
        h = body['hierarchy']
        area = copy.deepcopy(next(iter(h['areas'].values())))
        label = copy.deepcopy(next(iter(h['labels'].values())))
        h['labels'] = {key: {**label, 'id':key, 'name':'Space: '+name} for key,name in [('office','Office'),('studio','Studio'),('keli','Keli')]}
        h['labels']['new:label:fixture'] = {**label, 'id':'new:label:fixture', 'name':'Space: New space'}
        h['labels']['orphan'] = {**label, 'id':'orphan', 'name':'Space: Unplaced', 'description':None}
        h['labels']['solo'] = {**label, 'id':'solo', 'name':'Space: Solo', 'description':None}
        rows = [('coffee','Coffee','first',['office']),('meeting','Meeting','first',['office']),('desk','Desk','first',['office']),('unassigned','Unassigned','first',[]),('studio_area','Studio area','second',['studio']),('keli_area','Keli area','second',['keli']),('remote','Remote','second',['office']),('loose','Loose',None,[]),('conflict','Ambiguous room','first',['office','studio']),('pending','Pending','first',['office']),('new_area','New area','second',['new:label:fixture'])]
        rows.append(('solo_area','Solo room','third',['solo']))
        h['areas'] = {key:{**area,'id':key,'name':name,'floorId':floor,'labels':labels,'entityIds':[],'deviceIds':[]} for key,name,floor,labels in rows}
        h['floors'] = [{'id':'first','name':'First','level':0,'areaIds':['coffee','meeting','desk','unassigned','conflict','pending']},{'id':'second','name':'Second','level':1,'areaIds':['studio_area','keli_area','remote','new_area']}]
        h['looseAreaIds']=['loose']; h['entities']={}; h['devices']={}; h['unassignedEntityIds']=[]
        h['floors'].append({'id':'third','name':'Third','level':2,'areaIds':['solo_area']})
        h['floors'].append({'id':'empty','name':'Empty floor','level':3,'areaIds':[]})
        changes=[{'id':2,'kind':'label','op':'create','targetId':'new:label:fixture','scope':None,'before':{},'after':{'name':'Space: New space'},'createdAt':''},{'id':3,'kind':'area','op':'update','targetId':'new_area','scope':None,'before':{'labels':[]},'after':{'labels':['new:label:fixture']},'createdAt':''},{'id':1,'kind':'area','op':'update','targetId':'pending','scope':None,'before':{'labels':[]},'after':{'labels':['office']},'createdAt':''}]
        with sync_playwright() as p:
            browser=launch(p); context=browser.new_context(viewport={'width':1600,'height':1000}); page=context.new_page()
            def guard(route):
                if route.request.method not in ('GET','HEAD','OPTIONS'): self.fail('Unexpected write: '+route.request.url)
                route.continue_()
            page.route('**/api/**',guard)
            page.route('**/api/hierarchy*',lambda r:r.fulfill(json=body))
            submitted=[]
            def mock_changes(route):
                if route.request.method == 'POST':
                    item=route.request.post_data_json; submitted.append(item)
                    fields=item['fields']; key='new:'+item['kind']+':'+str(len(submitted))
                    changes.append({'id':100+len(submitted),'kind':item['kind'],'op':'create','targetId':key,'scope':None,'before':{},'after':fields,'createdAt':''})
                    if item['kind']=='label': h['labels'][key]={**label,'id':key,'name':fields['name'],'description':fields['description']}
                    if item['kind']=='area':
                        floor=fields.get('floor_id'); h['areas'][key]={**area,'id':key,'name':fields['name'],'floorId':floor,'labels':fields.get('labels',[]),'entityIds':[],'deviceIds':[]}
                        if floor is None: h['looseAreaIds'].append(key)
                        else: next(f for f in h['floors'] if f['id']==floor)['areaIds'].append(key)
                route.fulfill(json={'ok':True,'changes':changes,'version':'mock'})
            page.route('**/api/settings/general',lambda r:r.fulfill(json={'ok':True,'general':{'reviewChangesBeforeApplying':True},'revision':'mock'}))
            page.route('**/api/changes',mock_changes)
            page.goto(BASE+'/#home',wait_until='networkidle')
            nav=page.get_by_role('navigation',name='Floors and areas')
            expect(nav.get_by_role('button',name='Office',exact=True)).to_have_count(2)
            expect(nav.get_by_role('button',name='Studio',exact=True)).to_have_count(1)
            expect(nav.get_by_role('button',name='Keli',exact=True)).to_have_count(1)
            for name in ['Coffee','Meeting','Desk','Studio area','Keli area','Remote','Loose','Ambiguous room','Pending','New area']:
                expect(nav.get_by_role('button',name=re.compile('^' + re.escape(name) + r'(?:\s|$)'))).to_have_count(1)
            expect(nav.get_by_role('button',name='Conflicting Spaces')).to_have_count(1)
            expect(nav.get_by_role('button',name='No Space',exact=True)).to_have_count(5)
            for floor_name in ['Empty floor', 'Third', 'No floor']:
                expect(nav.get_by_role('button',name='Add area to No Space on '+floor_name,exact=True)).to_be_visible()
            h['looseAreaIds']=[]
            orphan=h['labels'].pop('orphan')
            page.get_by_role('button',name='Refresh',exact=True).click()
            expect(nav.get_by_role('button',name='Add area to No Space on No floor',exact=True)).to_be_visible()
            h['looseAreaIds']=['loose']
            h['labels']['orphan']=orphan
            page.get_by_role('button',name='Refresh',exact=True).click()
            name_input=page.get_by_label('New Space name')
            name_input.fill('Draft Space')
            assignment=page.get_by_label('Space for Unassigned')
            assignment.select_option('office')
            studio=page.locator('div').filter(has=page.get_by_text('Studio',exact=True)).filter(has=page.get_by_role('button',name='Rename',exact=True)).last
            studio.get_by_role('button',name='Rename',exact=True).click()
            rename=page.get_by_label('Space name',exact=True)
            rename.fill('Draft rename')
            page.once('dialog',lambda dialog:dialog.dismiss())
            studio.get_by_role('button',name='Cancel',exact=True).click()
            expect(rename).to_have_value('Draft rename')
            page.once('dialog',lambda dialog:dialog.accept())
            studio.get_by_role('button',name='Cancel',exact=True).click()
            expect(name_input).to_have_value('Draft Space')
            expect(assignment).to_have_value('office')
            page.get_by_role('button',name='Refresh',exact=True).click()
            expect(name_input).to_have_value('Draft Space')
            expect(assignment).to_have_value('office')
            removed=h['areas'].pop('unassigned')
            h['floors'][0]['areaIds'].remove('unassigned')
            page.get_by_role('button',name='Refresh',exact=True).click()
            expect(page.get_by_text('Area unassigned is no longer available',exact=False)).to_be_visible()
            page.get_by_role('button',name='Add assignments to Changes').click()
            expect(page.get_by_role('alert')).to_contain_text('Area unassigned is no longer available')
            h['areas']['unassigned']=removed
            h['floors'][0]['areaIds'].append('unassigned')
            page.get_by_role('button',name='Refresh',exact=True).click()
            expect(assignment).to_have_value('office')
            page.once('dialog',lambda dialog:dialog.dismiss())
            nav.get_by_role('button',name='First',exact=True).click()
            expect(name_input).to_have_value('Draft Space')
            expect(assignment).to_have_value('office')
            page.once('dialog',lambda dialog:dialog.accept())
            nav.get_by_role('button',name='First',exact=True).click()
            expect(name_input).to_have_count(0)
            nav.get_by_role('button',name='Home Assistant',exact=True).click()
            expect(nav.get_by_role('button',name='Unplaced',exact=True)).to_have_count(1)
            expect(nav.get_by_role('button',name='New space',exact=True)).to_have_count(1)
            nav.get_by_role('button',name='Solo',exact=True).click()
            page.get_by_label('Show empty areas').uncheck()
            expect(nav.get_by_role('button',name='Third',exact=True)).to_be_visible()
            expect(nav.get_by_role('button',name='Solo',exact=True)).to_have_attribute('aria-current','true')
            expect(nav.get_by_role('button',name='Solo room',exact=True)).to_have_count(0)
            page.get_by_label('Show empty areas').check()
            page.screenshot(path=str(screenshot_dir() / 'space-tree-mock.png'))
            first=nav.get_by_role('button',name='Office',exact=True).first
            nav.get_by_role('button',name='Collapse Office',exact=True).first.click(); expect(nav.get_by_role('button',name=re.compile(r'^Coffee\b'))).to_have_count(0)
            expect(nav.get_by_role('button',name=re.compile(r'^Remote\b'))).to_have_count(1)
            search=page.get_by_label('Find an area or entity'); search.fill('Coffee')
            expect(nav.get_by_role('button',name=re.compile(r'^Coffee\b'))).to_have_count(1)
            expect(nav.get_by_role('button',name=re.compile(r'^Remote\b'))).to_have_count(0)
            search.fill('Office'); expect(nav.get_by_role('button',name=re.compile(r'^Coffee\b'))).to_have_count(1); expect(nav.get_by_role('button',name=re.compile(r'^Remote\b'))).to_have_count(1)
            search.fill('Unplaced'); expect(nav.get_by_role('button',name='Unplaced',exact=True)).to_have_count(1)
            expect(nav.get_by_role('button',name=re.compile(r'^Studio area\b'))).to_have_count(0)
            search.fill(''); nav.get_by_role('button',name='Expand Office',exact=True).first.click()
            nav.get_by_role('button',name=re.compile(r'^Coffee\b')).click()
            expect(nav.get_by_role('button',name=re.compile(r'^Coffee\b'))).to_have_attribute('aria-current','true')
            nav.get_by_role('button',name='Collapse Office',exact=True).first.click(); expect(nav.get_by_role('button',name=re.compile(r'^Coffee\b'))).to_have_count(0)
            page.reload(wait_until='networkidle')
            expect(nav.get_by_role('button',name=re.compile(r'^Coffee\b'))).to_have_attribute('aria-current','true')
            page.set_viewport_size({'width':1600,'height':600})
            nav.evaluate('(node) => { node.scrollTop = node.scrollHeight; }')
            self.assertGreater(nav.evaluate('(node) => node.scrollTop'), 0)
            nav.get_by_role('button',name='Add area to Studio on Second',exact=True).click()
            form=nav.get_by_role('region',name='Create area')
            expect(form.get_by_label('New area')).to_be_focused()
            self.assertTrue(form.evaluate('(node) => { const a=node.getBoundingClientRect(), b=node.closest("nav").getBoundingClientRect(); return a.top >= b.top && a.bottom <= b.bottom; }'))
            form.get_by_role('button',name='Cancel').click()
            floor=nav.get_by_role('button',name='First',exact=True)
            expect(floor).to_have_attribute('aria-expanded','true')
            nav.get_by_role('button',name='Add Space to First',exact=True).click()
            expect(floor).to_have_attribute('aria-expanded','true')
            expect(nav.get_by_role('button',name=re.compile(r'^Coffee\b'))).to_have_attribute('aria-current','true')
            form=nav.get_by_role('region',name='Create Space')
            expect(form.get_by_label('New Space')).to_be_focused()
            self.assertGreater(form.bounding_box()['y'], floor.bounding_box()['y'])
            self.assertLess(form.bounding_box()['y'], first.bounding_box()['y'])
            form.get_by_label('New Space').fill('Office')
            form.get_by_role('button',name='Add',exact=True).click()
            expect(form.get_by_role('alert')).to_contain_text('already exists')
            form.get_by_label('New Space').fill('Zebra')
            page.screenshot(path=str(screenshot_dir() / 'space-tree-add-space.png'))
            form.get_by_role('button',name='Add',exact=True).click()
            expect(form).to_have_count(0)
            self.assertEqual(submitted[-1]['kind'], 'label')
            self.assertEqual(submitted[-1]['fields']['name'], 'Space: Zebra')
            self.assertIn('first', submitted[-1]['fields']['description'])
            zebra=nav.get_by_role('button',name='Zebra',exact=True)
            expect(zebra).to_have_count(1)
            page.reload(wait_until='networkidle'); expect(zebra).to_have_count(1)
            zebra_id=next(k for k,v in h['labels'].items() if v['name']=='Space: Zebra')
            nav.get_by_role('button',name='Add area to Zebra on First',exact=True).click()
            form=nav.get_by_role('region',name='Create area')
            self.assertGreater(form.bounding_box()['y'], zebra.bounding_box()['y'])
            for name in ['Zulu','Alpha']:
                form.get_by_label('New area').fill(name)
                if name=='Zulu': page.screenshot(path=str(screenshot_dir() / 'space-tree-add-area.png'))
                form.get_by_role('button',name='Add',exact=True).click()
                expect(form).to_have_count(0)
                self.assertEqual(submitted[-1], {'kind':'area','op':'create','fields':{'name':name,'floor_id':'first','labels':[zebra_id]}})
                if name=='Zulu': nav.get_by_role('button',name='Add area to Zebra on First',exact=True).click()
            self.assertLess(nav.get_by_role('button',name=re.compile(r'^Alpha\b')).bounding_box()['y'], nav.get_by_role('button',name=re.compile(r'^Zulu\b')).bounding_box()['y'])
            page.get_by_label('Show empty areas').uncheck()
            expect(zebra).to_have_count(1)
            expect(nav.get_by_role('button',name=re.compile(r'^Alpha\b'))).to_have_count(0)
            page.get_by_label('Show empty areas').check()
            page.reload(wait_until='networkidle')
            self.assertLess(nav.get_by_role('button',name=re.compile(r'^Alpha\b')).bounding_box()['y'], nav.get_by_role('button',name=re.compile(r'^Zulu\b')).bounding_box()['y'])
            page.screenshot(path=str(screenshot_dir() / 'space-tree-sorted-areas.png'))
            nav.get_by_role('button',name='Add area to Zebra on First',exact=True).click()
            form.get_by_label('New area').fill('Unsaved')
            page.once('dialog', lambda dialog: dialog.dismiss())
            nav.get_by_role('button',name='Add Space to Second',exact=True).click()
            expect(form.get_by_label('New area')).to_have_value('Unsaved')
            page.once('dialog', lambda dialog: dialog.accept())
            nav.get_by_role('button',name='Add Space to Second',exact=True).click()
            expect(nav.get_by_role('region',name='Create Space')).to_be_visible()
            nav.get_by_role('region',name='Create Space').get_by_role('button',name='Cancel').click()
            nav.get_by_role('button',name='Add area to Office on First',exact=True).click()
            form=nav.get_by_role('region',name='Create area')
            expect(form).to_contain_text('Space: Office')
            form.get_by_label('New area').fill('Office child')
            form.get_by_role('button',name='Add',exact=True).click()
            expect(form).to_have_count(0)
            self.assertEqual(submitted[-1], {'kind':'area','op':'create','fields':{'name':'Office child','floor_id':'first','labels':['office']}})
            expect(nav.get_by_role('button',name='Add area to Conflicting Spaces on First')).to_have_count(0)
            for floor_name, fields in [('First', {'name':'Unassigned child','floor_id':'first'}), ('No floor', {'name':'Loose child'})]:
                add=nav.get_by_role('button',name='Add area to No Space on '+floor_name,exact=True)
                expect(add).to_be_visible()
                add.click()
                form=nav.get_by_role('region',name='Create area')
                expect(form).to_contain_text('New area on '+floor_name)
                expect(form).not_to_contain_text('Space: No Space')
                self.assertGreater(form.bounding_box()['y'], add.bounding_box()['y'])
                form.get_by_label('New area').fill(fields['name'])
                if floor_name == 'First': page.screenshot(path=str(screenshot_dir() / 'space-tree-no-space-add.png'))
                form.get_by_role('button',name='Add',exact=True).click()
                expect(form).to_have_count(0)
                self.assertEqual(submitted[-1], {'kind':'area','op':'create','fields':fields})
            previewed=[]
            def preview(route):
                body=route.request.post_data_json
                previewed.extend(body['changes'])
                planned=[{'id':i+1,'kind':item['kind'],'op':item['op'],'targetId':'new:area:1','scope':None,'before':{},'after':item['fields'],'createdAt':''} for i,item in enumerate(body['changes'])]
                route.fulfill(json={'ok':True,'changes':planned,'previewVersion':'mock','requiresNoBackupConfirmation':False})
            page.route('**/api/settings/general',lambda r:r.fulfill(json={'ok':True,'general':{'reviewChangesBeforeApplying':False},'revision':'mock','directEditingAvailable':True}))
            page.route('**/api/direct-preview',preview)
            page.reload(wait_until='networkidle')
            nav.get_by_role('button',name='Add area to Office on First',exact=True).click()
            form.get_by_label('New area').fill('Direct child')
            form.get_by_role('button',name='Add',exact=True).click()
            dialog=page.get_by_role('dialog',name='Review before applying')
            expect(dialog).to_be_visible()
            self.assertEqual(previewed[-1], {'kind':'area','op':'create','fields':{'name':'Direct child','floor_id':'first','labels':['office']}})
            dialog.get_by_role('button',name='Cancel').click()
            applied=[]
            def direct(route):
                applied.append(route.request.post_data_json)
                route.fulfill(json={'ok':True,'results':[],'applied':1,'failed':0})
            page.route('**/api/direct-changes',direct)
            self.assertEqual(applied, [])
            form.get_by_role('button',name='Add',exact=True).click()
            dialog.get_by_role('button',name='Confirm and apply').click()
            expect(form).to_have_count(0)
            self.assertEqual(applied[-1]['changes'][0]['fields'], {'name':'Direct child','floor_id':'first','labels':['office']})
            nav.get_by_role('button',name='Add Space to Second',exact=True).click()
            space_form=nav.get_by_role('region',name='Create Space')
            space_form.get_by_label('New Space').fill('Direct Space')
            space_form.get_by_role('button',name='Add',exact=True).click()
            expect(dialog).to_be_visible()
            self.assertEqual(previewed[-1]['fields']['name'], 'Space: Direct Space')
            self.assertIn('second', previewed[-1]['fields']['description'])
            dialog.get_by_role('button',name='Cancel').click()
            self.assertEqual(len(applied), 1)
            context.close(); browser.close()

if __name__ == '__main__': unittest.main()
